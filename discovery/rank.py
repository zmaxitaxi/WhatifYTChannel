"""Rank the topic slate and write docs/research/topic_ranking.md.

Usage:
    python3 -m discovery.rank            # print the ranking
    python3 -m discovery.rank --write    # also regenerate the Markdown report
"""

from __future__ import annotations

import argparse
from pathlib import Path

from .topics import WEIGHTS, RankResult, load_topics, rank

ROOT = Path(__file__).resolve().parent.parent
TOPICS_FILE = Path(__file__).parent / "data" / "topics.json"
REPORT_FILE = ROOT / "docs" / "research" / "topic_ranking.md"

SHORT = {
    "trend_strength": "Trend",
    "visual_potential": "Visual",
    "originality": "Orig.",
    "rendering_feasibility": "Feas.",
    "novelty": "Novelty",
}


def to_markdown(result: RankResult) -> str:
    lines = [
        "# Topic ranking",
        "",
        "Generated by `python3 -m discovery.rank --write` from `discovery/data/topics.json`. Edit the JSON, not this file.",
        "",
        "Score = " + " + ".join(f"{w:.2f} × {k}" for k, w in WEIGHTS.items()) + ", each term 0–100.",
        "",
        "Trend, visual, originality and feasibility are human estimates made on 2026-10-31 without YouTube API data. "
        "Novelty is computed: it drops when other topics on the slate share the scenario family or a named institution. "
        "Replace trend estimates with measured competitor view velocity once `discovery.competitors observe` has run twice.",
        "",
        "## Ranked",
        "",
        "| Rank | ID | Topic | Family | " + " | ".join(SHORT.values()) + " | Score |",
        "|---:|---|---|---|" + "---:|" * len(SHORT) + "---:|",
    ]
    for i, (t, total, terms) in enumerate(result.ranked, 1):
        cells = " | ".join(f"{terms[k]:.0f}" for k in SHORT)
        lines.append(f"| {i} | {t.id} | {t.title} | {t.scenario_family} | {cells} | **{total:.1f}** |")

    lines += ["", "## Rejected before ranking", ""]
    if result.rejected:
        for t, reason in result.rejected:
            lines.append(f"- **{t.id}** {t.title}: {reason}.")
    else:
        lines.append("None.")

    near = [m for m in result.duplicates if m.kind == "near"]
    lines += ["", "## Near duplicates to review", "", "These stay ranked; a person decides whether to keep both.", ""]
    if near:
        for m in near:
            lines.append(f"- **{m.topic_id}** vs **{m.other_id}**: {m.reason}.")
    else:
        lines.append("None.")

    lines += ["", "## Why each topic scored as it did", ""]
    for t, total, _ in result.ranked:
        lines.append(f"### {t.id}: {t.title} ({total:.1f})")
        lines.append("")
        for k in SHORT:
            if k in t.rationale:
                lines.append(f"- {SHORT[k]}: {t.rationale[k]}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--topics", type=Path, default=TOPICS_FILE)
    parser.add_argument("--write", action="store_true", help=f"write {REPORT_FILE.relative_to(ROOT)}")
    args = parser.parse_args(argv)

    result = rank(load_topics(args.topics))
    for i, (t, total, _) in enumerate(result.ranked, 1):
        print(f"{i:>2}. {total:5.1f}  {t.id}  {t.title}")
    for t, reason in result.rejected:
        print(f"    rejected {t.id}: {reason}")
    for m in result.duplicates:
        if m.kind == "near":
            print(f"    near-dup {m.topic_id} ~ {m.other_id}: {m.reason}")
    if args.write:
        REPORT_FILE.parent.mkdir(parents=True, exist_ok=True)
        REPORT_FILE.write_text(to_markdown(result), encoding="utf-8")
        print(f"Wrote {REPORT_FILE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
